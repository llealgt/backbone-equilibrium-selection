"""Stage-E driver: the pre-registered confirmatory replication.

Everything this script runs is fixed by `stageE_config.json`, which is part of
the registered material. The training call is the same `nbn.train` call used by
stageC.py / stageD.py, with the same hyperparameters; only the seeds are new.

Usage
    python stageE.py parallel 18     # run every registered job across 18 processes
    python stageE.py merge           # merge shard files into stageE_cache.json
    python stageE.py smoke           # 2 jobs on OLD seeds (0,1): checks the code path
                                     # reproduces Stage D, writes nothing to the cache

Do not edit this file or the config after registration. Any change must be
reported as a deviation in the paper.
"""
import json, os, sys, time, glob, hashlib
import numpy as np
import efg, nbn, games2

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG_PATH = os.path.join(HERE, "stageE_config.json")
CFG = json.load(open(CONFIG_PATH))
CACHE = CFG["cache_file"]

# arm name -> nbn.train keyword arguments (copied from stageC.BASE / stageD.ARMS)
ARMS = {
    "mlp":       dict(arch="mlp",  opt_lr=0.015, h=16),           # Stage B/C arm
    "attn":      dict(arch="attn", opt_lr=0.012, h=16, d=8),      # Stage B/C arm
    "mlp_lr012": dict(arch="mlp",  opt_lr=0.012, h=16),           # Stage D arm
    "attn_cap":  dict(arch="attn", opt_lr=0.012, h=16, d=11),     # Stage D arm
    "attn_cap15": dict(arch="attn", opt_lr=0.015, h=16, d=11),    # Stage D arm
}
TRAIN = dict(iters=1500, inner=3, ref_period=40, eta=0.5)


def games():
    G = {"kuhn": efg.GAMES["kuhn"]}
    G.update({n: g for n, (g, _) in games2.GAMES2.items()})
    return G


def jobs():
    """(block, game, arm, seed) for every registered run, in registration order."""
    J = []
    for blk in CFG["blocks"]:
        for gname in blk["games"]:
            for arm in blk["arms"]:
                for s in range(blk["seed_start"], blk["seed_start"] + blk["n_per_arm"]):
                    J.append((blk["name"], gname, arm, s))
    return J


def key(j):
    return "%s|%s|%s|%d" % j


def run_one(G, F, gname, arm, seed):
    cfg = dict(ARMS[arm]); arch = cfg.pop("arch")
    r = nbn.train(G[gname], arch=arch, seed=seed, F=F[gname], **TRAIN, **cfg)
    rec = dict(coord=r["coord"], exploit=r["exploit"], entropy=r["entropy"],
               final_exploit=r["final_exploit"], coord_final=r["coord_final"],
               coord_late=r["coord_late"], entropy_final=r["entropy_final"],
               nparams=r["nparams"], numeric_ok=r["numeric_ok"],
               sigma={repr(k): list(map(float, v)) for k, v in r["sigma"].items()})
    if gname != "kuhn":
        rec.update(G[gname].aux_coords(r["sigma"]))
    return rec


def main(shard=0, nshards=1):
    path = CACHE.replace(".json", "_s%d.json" % shard)
    cache = json.load(open(path)) if os.path.exists(path) else {}
    G = games(); F = {n: nbn.build_features(g) for n, g in G.items()}
    t0 = time.time()
    for i, j in enumerate(jobs()):
        if i % nshards != shard or key(j) in cache:
            continue
        cache[key(j)] = run_one(G, F, *j[1:])
        json.dump(cache, open(path, "w"))
    print("shard %d done (%.0fs)" % (shard, time.time() - t0), flush=True)


def merge():
    out = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
    for f in sorted(glob.glob(CACHE.replace(".json", "_s*.json"))):
        out.update(json.load(open(f)))
    json.dump(out, open(CACHE, "w"), sort_keys=True)
    todo = [key(j) for j in jobs() if key(j) not in out]
    print("merged -> %s : %d runs, %d missing" % (CACHE, len(out), len(todo)))
    return out


def run_parallel(nproc):
    import multiprocessing as mp
    print("launching %d shards over %d registered jobs" % (nproc, len(jobs())))
    ps = [mp.Process(target=main, args=(i, nproc)) for i in range(nproc)]
    [p.start() for p in ps]; [p.join() for p in ps]
    return merge()


def smoke():
    """Runs two OLD-seed jobs (Stage D seeds 0 and 1, Kuhn, matched arms) and prints
    them. Seeds 0-1 are already in Stage D, so this produces no new data."""
    G = games(); F = {"kuhn": nbn.build_features(G["kuhn"])}
    for arm in ("mlp_lr012", "attn_cap"):
        for s in (0, 1):
            r = run_one(G, F, "kuhn", arm, s)
            print("smoke kuhn %-10s seed %d coord=%.6f exploit=%.6f" % (arm, s, r["coord"], r["exploit"]))


def fingerprint():
    """sha256 of this script, the config and the modules it imports."""
    h = {}
    for f in ("stageE.py", "stageE_config.json", "analyzeE.py", "efg.py", "nbn.py",
              "games2.py", "selstats.py"):
        h[f] = hashlib.sha256(open(os.path.join(HERE, f), "rb").read()).hexdigest()
    return h


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "parallel":
        run_parallel(int(a[1]) if len(a) > 1 else os.cpu_count())
    elif a and a[0] == "merge":
        merge()
    elif a and a[0] == "smoke":
        smoke()
    elif a and a[0] == "fingerprint":
        print(json.dumps(fingerprint(), indent=1))
    else:
        print(__doc__)
